const assert=require('node:assert/strict');
const {upgrade,recordElementUpdates,prepareElement}=require('../static/eval_catalog/catalog.js');
const seed=JSON.parse(require('node:fs').readFileSync(process.argv[2],'utf8'));
const legacy=structuredClone(seed);
for(const kind of ['stages','stories','skills','factors']){
 assert(seed[kind].every(row=>row.update_history.length===2));
 legacy[kind].forEach(row=>{row.update_history=[];});
}
const migrated=upgrade(seed,legacy);
for(const kind of ['stages','stories','skills','factors'])assert.deepEqual(migrated[kind][0].update_history,seed[kind][0].update_history);
legacy.stages[0].updated_at='2026-09-21 12:00:00';
assert.deepEqual(upgrade(seed,legacy).stages[0].update_history,[]);
// Isolate real-edit history assertions from seeded demonstration history.
for(const kind of ['stages','stories','skills','factors'])seed[kind].forEach(row=>{row.update_history=[];});
const db=upgrade(seed,null),before=JSON.stringify(db);
const tags=[{id:'act_pick',name:'动作标签 / 拿放类 / 拿取'}];
const firstTime='2026-09-21 10:00:00',secondTime='2026-09-21 10:01:00';
for(const kind of ['stages','stories','skills','factors']){
 const next=structuredClone(db),row=next[kind][0],original=db[kind][0];
 const field=kind==='skills'?'name_en':kind==='factors'?'dimension':'name';
 row[field]+=' updated';row.tag_ids=['act_pick'];row.project=original.project==='预训练评测'?'后训练评测':'预训练评测';
 const updated=recordElementUpdates(db,next,tags,firstTime),saved=updated[kind][0];
 assert.equal(saved.update_history.length,1);
 const entry=saved.update_history[0];
 assert.equal(entry.updated_at,firstTime);assert.equal(entry.updated_by,'Joanna Qiao');
 assert.equal(saved.created_by,original.created_by);assert.equal(saved.updated_by,'Joanna Qiao');
 assert.equal(entry.changes.find(c=>c.field===field).before,original[field]);
 assert.equal(entry.changes.find(c=>c.field===field).after,row[field]);
 assert.equal(entry.changes.find(c=>c.field==='tag_ids').after_text,tags[0].name);
 const repeat=structuredClone(updated);repeat[kind][0].updated_at=secondTime;
 const unchanged=recordElementUpdates(updated,repeat,tags,secondTime)[kind][0];
 assert.equal(unchanged.update_history.length,1);assert.equal(unchanged.updated_at,firstTime);
 const statusNext=structuredClone(updated);
 statusNext[kind][0].publish_status=original.publish_status==='已发布'?'未发布':'已发布';
 statusNext[kind][0].enabled=false;
 const statusSaved=recordElementUpdates(updated,statusNext,tags,secondTime);
 assert.equal(statusSaved[kind][0].update_history.length,2);
 assert.equal(statusSaved[kind][0].update_history[0].updated_at,secondTime);
 assert.equal(statusSaved[kind][0].update_history[0].changes.find(c=>c.field==='enabled').after_text,'停用');
 assert.deepEqual(upgrade(seed,statusSaved)[kind][0].update_history,statusSaved[kind][0].update_history);
 for(const other of ['stages','stories','skills','factors'].filter(key=>key!==kind))assert(statusSaved[other].every(r=>r.update_history.length===0));
}
const factorNext=structuredClone(db);factorNext.factors[0].values[0].description='修改后的说明';
const factorSaved=recordElementUpdates(db,factorNext,tags,firstTime);
const valueChange=factorSaved.factors[0].update_history[0].changes.find(c=>c.field==='values');
assert(valueChange.after_text.includes('说明：修改后的说明'));
assert.equal(valueChange.before[0].description,db.factors[0].values[0].description);
const hiddenNext=structuredClone(db);hiddenNext.factors[0].values[0].linked_factor_ids=['unrelated'];
assert.equal(recordElementUpdates(db,hiddenNext,tags,firstTime).factors[0].update_history.length,0);
const createdNext=structuredClone(db);
createdNext.stages.push(prepareElement(db,'stages',{name:'新增场域',project:'预训练评测',tag_ids:[]}));
const created=recordElementUpdates(db,createdNext,tags,firstTime).stages.at(-1);
assert.equal(created.update_history[0].changes.find(c=>c.field==='name').before,null);
assert.equal(created.update_history[0].changes.find(c=>c.field==='name').after,'新增场域');
assert.equal(JSON.stringify(db),before,'History generation must not mutate previous data');
console.log('Element history, snapshots, status changes, no-op saves and persistence passed.');
// Cases reuse the same audit schema without recording representation-only edits.
const caseNext=structuredClone(db),caseOld=db['test-cases'][0];
caseNext['test-cases'][0].prompt_cn='修改后的中文提示词';
caseNext['test-cases'][0].factors[0]={factor_id:caseOld.factors[0].factor_id,values:['小','适中']};
let caseSaved=recordElementUpdates(db,caseNext,tags,firstTime);
let caseRow=caseSaved['test-cases'][0];
assert.equal(caseRow.id,caseOld.id);
assert.equal(caseRow.update_history.length,1);
assert.equal(caseRow.update_history[0].updated_by,'Joanna Qiao');
assert(caseRow.update_history[0].changes.some(c=>c.field==='prompt_cn'));
assert(caseRow.update_history[0].changes.find(c=>c.field==='factors').after_text.includes('小'));
const reordered=structuredClone(caseSaved);
reordered['test-cases'][0].skill_ids.reverse();
reordered['test-cases'][0].factors[0].values.reverse();
reordered['test-cases'][0].case_stage=db.stories.find(r=>r.id===caseOld.story_id).stage_id;
caseSaved=recordElementUpdates(caseSaved,reordered,tags,secondTime);
assert.equal(caseSaved['test-cases'][0].update_history.length,1);
assert.equal(caseSaved['test-cases'][0].updated_at,firstTime);
const caseChanged=structuredClone(caseSaved);caseChanged['test-cases'][0].props='更新后的道具';
caseSaved=recordElementUpdates(caseSaved,caseChanged,tags,secondTime);
assert.equal(caseSaved['test-cases'][0].update_history.length,2);
assert.equal(caseSaved['test-cases'][0].update_history[0].updated_at,secondTime);
assert.deepEqual(upgrade(seed,caseSaved)['test-cases'][0].update_history,caseSaved['test-cases'][0].update_history);
console.log('Case history: real edits, factor values, no-op saves, newest first and persistence passed.');
