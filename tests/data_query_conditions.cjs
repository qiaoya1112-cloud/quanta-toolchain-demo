const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,channel:'chrome'});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[]; page.on('pageerror',e=>errors.push(e.message));
    const base=process.env.PREVIEW_URL||'http://127.0.0.1:5007/model/data/query';
    await page.goto(base);
    await page.screenshot({path:'/tmp/data-query-compact-default.png'});
    assert.equal(await page.locator('.query-filter-tabs').count(),0);
    assert.equal(await page.locator('.query-fixed-group[open]').count(),3);
    for(const id of ['qTaskFilters','qProcessingFilters','qPromptFilters','qExportFilters']) {
      assert.equal(await page.locator('#'+id).isVisible(),true);
    }
    const exportGroup=page.locator('#qVolume');
    await page.locator('#qExportFilters input[name=limit]').fill('9');
    assert.equal(await page.locator('section#qVolume').count(),1);
    assert.equal(await exportGroup.locator('summary,.query-disclosure').count(),0);
    assert.equal(await page.locator('#qExportFilters').isVisible(),true);
    assert.match(await exportGroup.locator('.query-stage-heading').innerText(),/已选 1 项/);
    assert.equal(await page.locator('#qTaskFilters').isVisible(),true);
    assert.equal(await page.locator('#qExportFilters input[name=limit]').inputValue(),'9');
    await page.locator('#qExportFilters input[name=limit]').fill('');
    const ids=()=>page.locator('#qbody tr[data-recording-id]').evaluateAll(rows=>rows.map(row=>row.dataset.recordingId));
    assert.equal(await page.locator('#qbody [data-exclude-id]').count(),0);
    const excludeId=async(id)=>{
      const input=page.locator('#qExcludedIds');
      const current=await input.inputValue();
      await input.fill([current,id].filter(Boolean).join(','));
      await page.locator('#qform button[type=submit]').click();
      await page.waitForLoadState('domcontentloaded');
    };
    const submit=async()=>{await Promise.all([page.waitForURL(url=>url.search.length>0),page.locator('#qform button[type=submit]').click()]);await page.waitForLoadState('domcontentloaded');};
    assert.equal((await ids()).length,10);
    await page.locator('#qAdvanced summary').click();
    const root=page.locator('#qConditionsBuilder > .query-condition-group');
    await root.getByRole('button',{name:'+ 添加条件',exact:true}).click();
    const first=root.locator(':scope > .query-condition-row').first();
    await first.getByLabel('字段',{exact:true}).selectOption('frames');
    await first.getByLabel('运算符',{exact:true}).selectOption('gte');
    assert.equal(await first.getByLabel('运算符',{exact:true}).locator('option:checked').innerText(),'大于等于');
    await first.getByLabel('值',{exact:true}).fill('1000');
    await root.getByRole('button',{name:'+ 添加条件组',exact:true}).click();
    const subgroup=root.locator(':scope > .query-condition-group');
    await subgroup.getByLabel('条件组关系',{exact:true}).selectOption('or');
    const groupFirst=subgroup.locator(':scope > .query-condition-row').first();
    await groupFirst.getByLabel('字段',{exact:true}).selectOption('task');
    await groupFirst.getByLabel('值',{exact:true}).fill('t1');
    await subgroup.getByRole('button',{name:'+ 添加条件',exact:true}).click();
    const groupSecond=subgroup.locator(':scope > .query-condition-row').nth(1);
    await groupSecond.getByLabel('字段',{exact:true}).selectOption('task');
    await groupSecond.getByLabel('值',{exact:true}).fill('t2');
    assert.equal(await page.locator('#qBuildDataset').isDisabled(),true);
    await submit();
    assert.deepEqual(await ids(),['121014','121005','120532','120502','120489']);
    assert.equal(await page.locator('.query-result-select,#qSelectPage,#qSelectionMenuTrigger,#qExcludeSelected').count(),0);
    assert.equal(await page.locator('#qBuildDataset').isEnabled(),true);
    assert.equal(await page.locator('#qAppendDataset').isEnabled(),true);
    assert.equal(await page.locator('#qAdvanced').getAttribute('open'),'');
    await page.locator('#qExclusions summary').click();
    const exclude=page.locator('#qExclusionsBuilder > .query-condition-group');
    await exclude.getByRole('button',{name:'+ 添加条件',exact:true}).click();
    await exclude.getByLabel('值',{exact:true}).fill('120502');
    await page.locator('#qExcludedIds').fill('121014');
    await page.locator('#qform button[type=submit]').click();
    await page.waitForLoadState('domcontentloaded');
    assert.deepEqual(await ids(),['121005','120532','120489']);
    assert.match(await page.locator('#qResMeta').innerText(),/筛选命中 5 条 · 已剔除 2 条 · 保留 3 条/);
    await page.locator('#qBuildDataset').click();
    assert.equal(await page.locator('#qBuildSelectionSummary').count(),0);
    await page.locator('#buildDsDrawer .drawer-close').click();
    await excludeId('121005');
    await excludeId('120532');
    assert.deepEqual(await ids(),['120489']);
    await page.getByRole('button',{name:'恢复数据 121005',exact:true}).click();
    await page.locator('#qform button[type=submit]').click();
    await page.waitForLoadState('domcontentloaded');
    assert.deepEqual(await ids(),['121005','120489']);
    await excludeId('121005');
    await excludeId('120489');
    assert.deepEqual(await ids(),[]);
    assert.equal(await page.locator('#qBuildDataset').isDisabled(),true);
    await page.locator('#qClearExclusions').click();
    await page.locator('#qform button[type=submit]').click();
    await page.waitForLoadState('domcontentloaded');
    assert.equal((await ids()).length,5);
    await page.locator('#qConditionsBuilder > .query-condition-group > .query-group-actions').getByRole('button',{name:'+ 添加条件',exact:true}).click();
    const url=page.url();
    await page.locator('#qform button[type=submit]').click();
    assert.equal(page.url(),url);
    assert.match(await page.locator('#qConditionError').innerText(),/完整填写/);
    await page.locator('#qConditionsBuilder > .query-condition-group > .query-condition-row').last().getByRole('button',{name:'移除',exact:true}).click();
    await page.locator('#qExclusions summary').click();
    await page.locator('#qExclusionsBuilder').getByRole('button',{name:'+ 添加条件',exact:true}).click();
    await page.locator('#qExclusionsBuilder').getByLabel('字段',{exact:true}).selectOption('qa_status');
    await page.locator('#qExclusionsBuilder').getByLabel('值',{exact:true}).selectOption('fail');
    await page.locator('#qform button[type=submit]').click();
    await page.waitForLoadState('domcontentloaded');
    await page.evaluate(()=>{document.documentElement.style.scrollBehavior='auto';window.scrollTo(0,document.getElementById('qAdvanced').getBoundingClientRect().top+window.scrollY-70);});
    await page.screenshot({path:'/tmp/data-query-advanced-desktop.png'});
    await page.setViewportSize({width:1024,height:900});
    await page.evaluate(()=>window.scrollTo(0,document.getElementById('qAdvanced').getBoundingClientRect().top+window.scrollY-70));
    await page.screenshot({path:'/tmp/data-query-advanced-1024.png'});
    await page.goto(base);
    await page.locator('#qAdvanced summary').click();
    await page.locator('#qConditionsBuilder').getByRole('button',{name:'+ 添加条件',exact:true}).click();
    const multiRow=page.locator('#qConditionsBuilder .query-condition-row');
    await multiRow.getByLabel('字段',{exact:true}).selectOption('qa_status');
    await multiRow.getByLabel('运算符',{exact:true}).selectOption('in');
    await multiRow.locator('.ms-trigger').click();
    await multiRow.getByLabel('合格',{exact:true}).check();
    await multiRow.getByLabel('操作失误',{exact:true}).check();
    assert.equal(await multiRow.locator('.ms-label').innerText(),'合格, 操作失误');
    const menu=await multiRow.locator('.ms-panel').boundingBox();
    assert.ok(menu&&menu.height>80);
    await page.screenshot({path:'/tmp/data-query-multi.png'});
    await page.locator('#qform button[type=submit]').click();
    await page.waitForLoadState('domcontentloaded');
    assert.equal((await ids()).length,9);
    assert.equal(await page.locator('#qConditionsBuilder .ms-label').innerText(),'合格, 操作失误');
    await excludeId((await ids())[0]);
    assert.equal((await ids()).length,8);
    assert.deepEqual(errors,[]);
    console.log('PASS: nested AND/OR, form state, exclusions by rule/ID/selection, restore, empty result, counts, dataset count, validation, and no browser errors.');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
