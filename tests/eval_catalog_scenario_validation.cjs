const assert=require('node:assert/strict');
const {upgrade,scenarioValueRows,scenarioCaseCount,saveScenarioRow,deleteScenarioRow,batchScenarios}=require('../static/eval_catalog/catalog.js');
const seed=JSON.parse(require('node:fs').readFileSync(process.argv[2],'utf8'));
const db=upgrade(seed,null),rows=scenarioValueRows(db);
const unused=rows.find(row=>row.publish_status==='已发布'&&row.factor_value&&scenarioCaseCount(db,row)===0);
const used=rows.find(row=>scenarioCaseCount(db,row)>0);
assert(unused&&used);
const original=JSON.stringify(db);
const changes={...unused,stage_id:'changed',story_id:'changed',skill_id:'changed',factor_id:'changed',factor_value:'changed',notes:'场景备注',project:'后训练评测',tag_ids:['act_pick'],updated_at:'2026-09-20 12:00:00'};
const edited=saveScenarioRow(db,changes);
const editedRow=scenarioValueRows(upgrade(seed,edited)).find(row=>row.row_key===unused.row_key);
for(const key of ['stage_id','story_id','skill_id','factor_id','factor_value','created_by','created_at'])assert.equal(editedRow[key],unused[key]);
assert.equal(editedRow.notes,'场景备注');
assert.equal(editedRow.project,'后训练评测');
assert.deepEqual(editedRow.tag_ids,['act_pick']);
assert.deepEqual(edited.stories,db.stories);
assert.throws(()=>saveScenarioRow(db,{...changes,project:'无效'}),/所属项目/);
const deleted=deleteScenarioRow(edited,unused.row_key);
const remaining=scenarioValueRows(upgrade(seed,deleted));
assert.equal(remaining.length,rows.length-1);
assert(!remaining.some(row=>row.row_key===unused.row_key));
assert.deepEqual(remaining,scenarioValueRows(upgrade(seed,db)).filter(row=>row.row_key!==unused.row_key),'Deleting one row preserves all siblings');
assert.equal(JSON.stringify(db),original,'Source data must not be mutated');
assert.deepEqual(deleted.stories,db.stories);
assert.throws(()=>deleteScenarioRow(db,used.row_key),/已有评测用例/);
const lateCase=structuredClone(db);
lateCase['test-cases'].push({id:'LATE_CASE',case_stage:unused.stage_id,story_id:unused.story_id,skill_ids:[unused.skill_id],factors:[{factor_id:unused.factor_id,values:[unused.factor_value]}],publish_status:'未发布',enabled:false});
assert.throws(()=>deleteScenarioRow(lateCase,unused.row_key),/已有评测用例/,'Recheck new cases regardless of their status');
assert.throws(()=>saveScenarioRow(deleted,changes),/已不存在/);
const added=batchScenarios(deleted,{stage_ids:[unused.stage_id],story_ids:[unused.story_id],skill_ids:[unused.skill_id],factors:[{factor_id:unused.factor_id,values:[unused.factor_value]}]},'later');
assert.equal(added.length,1,'A deleted scene can be added again');
const withAdded={...deleted,scenarios:[...deleted.scenarios,...added]};
const addedRow=scenarioValueRows(withAdded).find(row=>row.id===added[0].id&&row.scenario_record);
assert(addedRow);
assert.equal(scenarioValueRows(deleteScenarioRow(withAdded,addedRow.row_key)).length,rows.length-1);
console.log('Scenario metadata restrictions, per-value deletion, case protection and persistence passed.');
